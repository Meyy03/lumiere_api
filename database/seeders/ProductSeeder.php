    /**
     * Decide the default shopping audience for seeded products.
     *
     * You can override any individual product by adding:
     * 'target_audience' => 'female', 'male', or 'all'
     * inside that product's array.
     */
    private function resolveTargetAudience(array $product): string
    {
        $explicitAudience = $product['target_audience'] ?? null;

        if (
            is_string($explicitAudience) &&
            in_array($explicitAudience, ['female', 'male', 'all'], true)
        ) {
            return $explicitAudience;
        }

        /**
         * Makeup products in this catalog are primarily
         * placed in the Women recommendation group.
         */
        $femaleCategories = [
            'Lipstick',
            'Blush',
            'Eye Shadow',
            'Cushion',
            'Concealer',
            'Eye Liner',
            'Powder',
        ];

        if (in_array($product['category'], $femaleCategories, true)) {
            return 'female';
        }

        /**
         * A few fragrance products are used as
         * Men-specific recommendations.
         */
        $maleProductIds = [
            2311, // Fresh Citrus Eau de Parfum
            2312, // Warm Sandalwood Eau de Parfum
            2314, // Clean Linen Eau de Parfum
        ];

        if (in_array((int) $product['id'], $maleProductIds, true)) {
            return 'male';
        }

        /**
         * Skincare, body care and the remaining fragrances
         * are available to everyone.
         */
        return 'all';
    }

    private function generateSizes(string $size): array
    {
        $text = trim($size);
        $lower = strtolower($text);

        if (str_contains($lower, 'sheet')) {
            return ['1 sheet', '5 sheets', '10 sheets'];
        }

        if (str_contains($lower, 'patch')) {
            if (preg_match('/[\d.]+/', $text, $match)) {
                $amount = (float) $match[0];
                $original = (int) round($amount);

                return [
                    round($original / 2) . ' patches',
                    $original . ' patches',
                    round($original * 1.5) . ' patches',
                ];
            }

            return ['30 patches', '60 patches', '90 patches'];
        }

        if (preg_match('/([\d.]+)\s*(ml|g|oz)/i', $text, $match)) {
            $amount = (float) $match[1];
            $unit = strtolower($match[2]);

            return [
                $this->formatSizeNumber($amount / 2) . ' ' . $unit,
                $this->formatSizeNumber($amount) . ' ' . $unit,
                $this->formatSizeNumber($amount * 2) . ' ' . $unit,
            ];
        }

        return ['Small', $text, 'Large'];
    }

    private function formatSizeNumber(float $value): string
    {
        if ($value === (float) ((int) $value)) {
            return (string) ((int) $value);
        }

        return rtrim(rtrim(number_format($value, 1, '.', ''), '0'), '.');
    }
